import type { Locale } from "@/config/store";
import { localeMeta, store } from "@/config/store";
import { getDict, type DictKey } from "@/lib/i18n";

/** Absolute URL on the production origin for a locale-less path ("" = locale home). */
export const absUrl = (locale: Locale, path = "") => `${store.siteUrl}/${locale}${path}`;

/** Serialises JSON-LD safely for a <script> tag (escapes `<` so `</script>` cannot break out). */
export const jsonLdHtml = (data: unknown) => ({ __html: JSON.stringify(data).replace(/</g, "\\u003c") });

/** Shared Open Graph fields so per-page `openGraph` objects don't drop siteName / locale / type. */
export const ogBase = (locale: Locale) => ({
  type: "website" as const,
  siteName: store.name,
  locale: localeMeta[locale].intl.replace("-", "_"),
  alternateLocale: Object.entries(localeMeta).filter(([l]) => l !== locale).map(([, m]) => m.intl.replace("-", "_")),
});

/**
 * The branded share image generated by app/[locale]/opengraph-image.tsx. Pages that set their own
 * `openGraph` replace the parent's (including file-based images), so pageMeta references it explicitly.
 */
export const defaultShareImage = (locale: Locale) => ({
  url: `/${locale}/opengraph-image`,
  width: 1200,
  height: 630,
  alt: `${store.name} — ${store.tagline[locale]}`,
});

export function organizationJsonLd(locale: Locale) {
  return {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "Organization",
        "@id": `${store.siteUrl}/#organization`,
        name: store.name,
        url: store.siteUrl,
        slogan: store.tagline[locale],
      },
      {
        "@type": "WebSite",
        "@id": `${store.siteUrl}/#website-${locale}`,
        name: store.name,
        url: absUrl(locale),
        inLanguage: locale,
        description: getDict(locale)["meta.description"],
        publisher: { "@id": `${store.siteUrl}/#organization` },
        potentialAction: {
          "@type": "SearchAction",
          target: { "@type": "EntryPoint", urlTemplate: `${absUrl(locale, "/search")}?q={search_term_string}` },
          "query-input": "required name=search_term_string",
        },
      },
    ],
  };
}

/** BreadcrumbList; Home is prepended automatically. Labels are already-localized strings or dictionary keys. */
export function breadcrumbJsonLd(locale: Locale, items: { name: string | { key: DictKey }; path: string }[]) {
  const dict = getDict(locale);
  const all = [{ name: { key: "nav.home" as DictKey }, path: "" }, ...items];
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: all.map((it, i) => ({
      "@type": "ListItem",
      position: i + 1,
      name: typeof it.name === "string" ? it.name : dict[it.name.key],
      item: absUrl(locale, it.path),
    })),
  };
}
